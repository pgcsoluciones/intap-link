import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import vm from 'node:vm'
const owner=readFileSync('web/src/components/appointments/AppointmentOwnerBar.tsx','utf8')
const productionApp=readFileSync('app/.env.production','utf8')
const previewApp=readFileSync('app/.env.preview','utf8')
const prodWeb=readFileSync('web/.env.production','utf8')
const previewWeb=readFileSync('web/.env.preview','utf8')
assert.match(productionApp,/^VITE_API_URL=https:\/\/api\.intaprd\.com$/m)
assert.match(prodWeb,/^VITE_APP_URL=https:\/\/app\.intaprd\.com$/m)
assert.match(previewApp,/^VITE_API_URL=https:\/\/app\.preview\.intaprd\.com$/m)
assert.match(previewWeb,/^VITE_APP_URL=https:\/\/app\.preview\.intaprd\.com$/m)
const match=owner.match(/function ownerSessionApiBase\(base:string\):string\{([\s\S]*?)\n\}/)
assert.ok(match,'owner-session host resolution function present')
const transform=vm.runInNewContext('(function(base){'+match[1]+'})',{URL})
assert.equal(transform('https://app.intaprd.com/api/v1/me/sponsored-profile/appointments'),'https://api.intaprd.com/api/v1/me/sponsored-profile/appointments')
assert.equal(transform('https://app.intaprd.com/api/v1/me/medical-profile/appointments'),'https://api.intaprd.com/api/v1/me/medical-profile/appointments')
assert.equal(transform('https://app.intaprd.com/api/v1/me/free/appointments'),'https://api.intaprd.com/api/v1/me/free/appointments')
assert.equal(transform('https://app.preview.intaprd.com/api/v1/me/sponsored-profile/appointments'),'https://app.preview.intaprd.com/api/v1/me/sponsored-profile/appointments')
assert.equal(transform('https://custom.example.com/api/v1/me/sponsored-profile/appointments'),'https://custom.example.com/api/v1/me/sponsored-profile/appointments')
assert.equal(transform('http://app.intaprd.com/api/v1/me/sponsored-profile/appointments'),'http://app.intaprd.com/api/v1/me/sponsored-profile/appointments')
assert.ok(owner.includes("fetch(ownerSessionApiBase(ownerApiBase)+'/public-context?username='+encodeURIComponent(username)"),'owner GET uses session host')
assert.ok(owner.includes("const target=ownerSessionApiBase(ownerApiBase)+'/requests/'"),'owner appointment actions use session host')
assert.ok(owner.includes("credentials:'include'"),'credentialed requests preserved')
assert.ok(owner.includes("const manageUrl=origin+String(context.manage_url"),'management link keeps app origin')
assert.ok(owner.includes("const settingsUrl=origin+String(context.settings_url"),'settings link keeps app origin')
assert.ok(owner.includes('if(!context)return null'),'owner bar remains fail-closed')
console.log('PASS: owner bar GET + actions share production API session; Preview and owner security unchanged')
