import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const selection=readFileSync('api/src/intap-active-account.ts','utf8')
const api=readFileSync('api/src/index.ts','utf8')
const home=readFileSync('api/src/account-home-route.ts','utf8')
const sponsored=readFileSync('api/src/sponsored-appointments.ts','utf8')
const appSelector=readFileSync('app/src/components/admin/IntapcardAccountSelector.tsx','utf8')
assert.match(api,/datetime\('now', '\+30 days'\)/)
assert.match(api,/buildSessionCookie\(sessionRaw, c, 30 \* 24 \* 60 \* 60\)/)
assert.match(selection,/const LOGIN_SESSION_MAX_AGE_SECONDS=30\*24\*60\*60/)
assert.match(selection,/Max-Age='\+LOGIN_SESSION_MAX_AGE_SECONDS,\{append:true\}/)
assert.doesNotMatch(selection,/Max-Age=43200/)
assert.match(selection,/m\[3\]!==fingerprint/)
