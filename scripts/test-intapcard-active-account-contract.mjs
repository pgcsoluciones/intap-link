import fs from 'node:fs'
import assert from 'node:assert/strict'
const read=p=>fs.readFileSync(p,'utf8')
const active=read('api/src/intap-active-account.ts')
const home=read('api/src/account-home-route.ts')
const access=read('api/src/sponsored-multiprofile-access.ts')
const sponsored=read('api/src/sponsored-profile-scope.ts')
const sponsoredControls=read('api/src/sponsored-account-controls.ts')
const worker=read('api/src/index.ts')
const medical=read('api/src/medical-profile-owner.ts')
const appointments=read('api/src/medical-appointments.ts')
const ownerBar=read('web/src/components/appointments/AppointmentOwnerBar.tsx')
const medProfile=read('web/src/components/medical-profile/KawMedProfile.tsx')
const chooser=read('app/src/components/admin/IntapcardAccountSelector.tsx')
const guard=read('app/src/components/admin/AdminGuard.tsx')
const sponsor=read('app/src/components/admin/sponsored/SponsorDashboard.tsx')
const sponsorMed=read('app/src/components/admin/sponsored/SponsorKawMed.tsx')
for(const kind of ['medical','medical_master','sponsor','sponsored','free','paid','trial']){
  assert.ok(active.includes("'"+kind+"'"),'Active account kind missing '+kind)
  assert.ok(home.includes("case '"+kind+"'"),'Ownership case missing '+kind)
}
assert.match(active,/cookieNames\(c\.env\)\.session/,'Selection must bind to actual login cookie')
assert.match(active,/crypto\.subtle\.digest\('SHA-256'/,'Selection must bind to session fingerprint')
assert.match(active,/HttpOnly; Secure; SameSite=Lax/,'Selection cookie must remain protected')
assert.match(active,/if\(!fingerprint\|\|m\[3\]!==fingerprint\)return null/,'Stale login must not select an older identity')
assert.match(home,/app.post\('\/api\/v1\/me\/intapcard\/active-account',requireUser/,'Selection requires authentication')
assert.match(home,/if\(!\/\^\[a-f0-9-\]\{36\}\$\/i\.test\(id\)\|\|!\(await ownedChoice/,'Account ownership check required before selecting')
assert.match(home,/await setIntapSelection\(c,\{kind,id\}\)/,'Single central account cookie required')
assert.match(home,/app.get\('\/api\/v1\/me\/intapcard\/active-account',requireUser/,'Route guard must be able to read selection')
assert.match(home,/app.post\('\/api\/v1\/me\/intapcard\/leave-account',requireUser/,'Operator can explicitly leave selected account')
assert.match(chooser,/apiPost\('\/me\/intapcard\/active-account'/,'Every account goes through unified selection')
assert.doesNotMatch(chooser,/apiPost\('\/sponsor\/context'/,'Selector must not select sponsor in a separate identity layer')
assert.match(guard,/apiGet\('\/me\/intapcard\/active-account'\)/,'Admin routes must verify active account')
assert.match(guard,/navigate\('\/admin\/accounts',\{replace:true\}\)/,'Stale routes must return to selector')
assert.match(access,/if\(!active\|\|active.kind!=='medical'\|\|active.id!==id\)return null/,'Doctor resolver must reject wrong active account')
assert.match(access,/\['sponsor','medical_master'\]\.includes\(active.kind\)/,'Sponsor resolver must respect account type')
assert.match(sponsored,/active.kind!=='sponsored'/,'Beneficiary must respect selected profile')
assert.match(sponsored,/active\?\.kind!=='sponsor'/,'Master sponsored profile must require sponsor selection')
assert.match(sponsoredControls,/active.kind!=='sponsored'/,'Destructive unlink cannot affect inactive sponsored profile')
for(const fn of ['enforceIntapMedicalSelection','enforceIntapSponsoredSelection']){
  assert.ok(worker.includes(fn),'API must enforce '+fn)
}
assert.match(worker,/app.use\('\/api\/v1\/sponsor\/\*'/,'Sponsor APIs must guard selected category')
assert.match(worker,/code:'intap_account_not_selected'/,'Blocked requests should identify cause')
assert.match(worker,/const classicPrefixes=\['\/api\/v1\/me\/profile'/,'Free and Link classic profile requests must honor active account')
assert.match(worker,/\['free','paid'\]\.includes\(active.kind\)/,'Non-Free selected account cannot edit Free or Link profile')
assert.match(medical,/if\(ownerScope\(c\)==='sponsor_master'\)return ensureSponsorMasterProfile/,'Master editor keeps explicit scope')
assert.match(appointments,/settings_url:isMaster\?'\/admin\/sponsor\/kawmed\?tab=profile':'\/admin\/medical'/,'Public profile must target correct editor by actual owner scope')
assert.match(appointments,/manage_url:isMaster\?'\/admin\/medical\/agenda\?scope=sponsor_master'/,'Master appointment link must preserve its scope')
assert.match(appointments,/is_master:isMaster/,'Owner bar must receive actual owner classification')
assert.match(worker,/endsWith\('\/appointments\/public-context'\)\)return next\(\)/,'Owner context must resolve slug instead of relying on query scope')
assert.match(guard,/path==='\/admin\/medical\/agenda'&&new URLSearchParams\(location.search\)\.get\('scope'\)==='sponsor_master'/,'Master agenda must remain within selected Master scope')
assert.match(ownerBar,/context\?\.is_master\?'\?scope=sponsor_master':''/,'Master owner actions must carry selected scope')
assert.match(ownerBar,/context.settings_url\|\|settingsPath/,'Owner bar uses server-verified editor URL')
assert.match(ownerBar,/else setContext\(null\)/,'Old owner controls must disappear when account changes')
assert.match(medProfile,/settingsPath="\/admin\/medical"/,'Doctor fallback remains for ordinary users')
assert.match(sponsor,/Cambiar cuenta/,'Sponsor can choose a different account explicitly')
assert.match(sponsorMed,/Cambiar cuenta/,'Medical Master can choose a different account explicitly')
assert.match(sponsorMed,/sponsorAccounts.length>1&&!isIntapMulticuenta/,'Special account must not switch sponsors from local dropdown')
console.log('INTAP explicit active session, sponsor/medical isolation and public owner links: OK')
