import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const api = await readFile('api/src/routes/demo-ai.ts', 'utf8')
const openai = await readFile('api/src/lib/openai-structured.ts', 'utf8')
const demo = await readFile('web/src/components/demo/KawvoLinkDemo.tsx', 'utf8')
const wizard = await readFile('web/src/components/demo/KawvoLinkDemoAi.tsx', 'utf8')
const viral = await readFile('api/src/routes/demo-viral.ts', 'utf8')
const app = await readFile('web/src/App.tsx', 'utf8')

assert.match(app, /path="\/demo\/ia"/, 'Debe existir /demo/ia')
assert.match(demo, /Crear mi demo con IA/, 'La Demo manual debe conservarse y ofrecer entrada IA')
assert.match(demo, /kawvo_demo_ai_draft_v1/, 'La IA debe entregar su resultado al editor Demo existente')
assert.match(demo, /IntapLinkGratisProfile/, 'Debe seguir usándose el renderer real')
assert.match(demo, /\/api\/v1\/public\/demo\/share/, 'Debe conservarse el snapshot viral existente')
assert.match(demo, /Compartir por WhatsApp/, 'Debe conservarse compartir por WhatsApp')
assert.match(demo, /isAiGenerated \? '' : DEFAULT_LOCATION/, 'Demo IA no debe heredar ubicación ficticia')
assert.match(demo, /\.slice\(0, 3\)/, 'Botones rápidos deben respetar máximo 3')
assert.match(wizard, /No crea una cuenta ni publica un perfil/, 'La UX debe aclarar temporalidad sin tecnicismos')
assert.match(wizard, /Acepto las condiciones de la Demo con IA/, 'Consentimiento explícito requerido')
assert.match(wizard, /Continuar sin IA/, 'Debe existir fallback manual')
assert.match(wizard, /Usar este mismo número para llamadas/, 'Debe soportar mismo número para llamadas')
assert.match(wizard, /Correo/, 'Debe aceptar correo opcional')
assert.doesNotMatch(wizard, /OPENAI_API_KEY|api\.openai\.com/, 'Frontend no puede contener secretos ni endpoint OpenAI')
assert.match(openai, /store:\s*false/, 'OpenAI debe usar store:false')
assert.match(openai, /safety_identifier/, 'Debe enviar safety_identifier')
assert.match(openai, /json_schema/, 'Debe usar Structured Outputs')
assert.match(openai, /AbortController/, 'Debe existir timeout')
assert.match(api, /\/api\/v1\/public\/demo\/ai\/generate/, 'Endpoint Demo IA separado')
assert.match(api, /DEMO_AI_SESSION_LIMIT/, 'Rate limit por sesión')
assert.match(api, /DEMO_AI_IP_LIMIT/, 'Rate limit por IP')
assert.match(api, /CF-Connecting-IP/, 'Debe usar señal de IP server-side')
assert.match(api, /consent_required/, 'Backend debe exigir consentimiento')
assert.match(api, /DEMO_AI_CATEGORIES/, 'Clasificación limitada al catálogo Kawvo')
assert.match(api, /Mantenimiento e instalaciones técnicas/, 'Categoría técnica esperada')
assert.match(api, /Automotriz y mecánica/, 'Categoría automotriz esperada')
assert.match(api, /Hogar, decoración y mobiliario/, 'Categoría interiores esperada')
assert.match(api, /Eventos y entretenimiento/, 'Categoría eventos esperada')
assert.match(api, /\^\(tecnico\|tecnica\)\$/, 'Técnico solo debe ser ambiguo')
assert.match(api, /aire acondicionado/, 'Técnico de aire debe poder resolverse')
assert.match(api, /professional_title: 80/, 'Límite de cargo')
assert.match(api, /bio: 300/, 'Límite bio')
assert.match(api, /services_max: 3/, 'Máximo 3 servicios')
assert.doesNotMatch(api, /INSERT INTO profiles|UPDATE profiles|INSERT INTO users|UPDATE users/, 'Demo IA no puede escribir perfil/usuario')
assert.doesNotMatch(api, /profile_products|profile_contact|profile_gallery/, 'Endpoint IA no toca datos reales de perfil')
for (const event of ['demo_ai_started','demo_ai_generated','demo_ai_needs_more_info','demo_ai_failed','demo_ai_completed','demo_ai_fallback']) {
  assert.match(viral, new RegExp(event), `Falta evento ${event}`)
}
console.log('✓ Demo IA contract: producto, privacidad, seguridad, manual + viralidad preservados')
