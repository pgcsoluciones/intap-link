import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const api=readFileSync('api/src/sponsor-commercial-sales.ts','utf8')
const view=readFileSync('web/src/components/sponsored/SponsoredProfile.tsx','utf8')
const bar=readFileSync('web/src/components/sponsored/SponsoredCommercialOwnerBar.tsx','utf8')
const admin=readFileSync('app/src/components/admin/sponsored/SponsoredDashboard.tsx','utf8')
const account=readFileSync('api/src/intap-active-account.ts','utf8')
const start=api.indexOf("app.get('/api/v1/me/sponsored-commercial-public-context'")
const end=api.indexOf('\nexport default app',start)
assert.ok(start>0&&end>start,'Commercial public-context is registered separately from admin endpoints')
const owner=api.slice(start,end)
assert.match(owner,/cookieNames\(c\.env\)\.session/)
assert.match(owner,/session_hash=\? AND expires_at>datetime\('now'\) AND revoked_at IS NULL/)
assert.match(owner,/WHERE lower\(username\)=\? AND user_id=\? LIMIT 1/)
assert.match(owner,/if\(!profile\)return c\.json\(\{ok:false,error:'Perfil no autorizado\.'\},403\)/)
assert.match(owner,/const master=String\(profile\.profile_role\|\|'beneficiary'\)==='sponsor_owner'/)
assert.match(owner,/SELECT 1 FROM sponsor_members sm JOIN sponsor_tenants st/)
assert.match(owner,/sm\.status='active' AND st\.is_active=1/)
assert.match(owner,/if\(!member\)return c\.json\(\{ok:false,error:'Patrocinador no autorizado\.'\},403\)/)
assert.match(owner,/if\(await sponsoredMultiProfileAccess\(c,userId\)\)/)
assert.match(owner,/const selected=await readIntapSelection\(c\)/)
assert.match(owner,/selected\.kind==='sponsor'&&selected\.id===String\(profile\.sponsor_id\|\|''\)/)
assert.match(owner,/selected\.kind==='sponsored'&&selected\.id===String\(profile\.id\|\|''\)/)
assert.match(owner,/if\(!allowed\)return c\.json\(\{ok:false,error:'Este perfil no es la cuenta activa\.'\},403\)/)
assert.match(owner,/module_code IN \('commercial_seller','commercial_visitor','commercial_catalog','commercial_vademecum'\)/)
assert.match(owner,/if\(!master&&\(enabled\.has\('commercial_seller'\)\|\|enabled\.has\('commercial_visitor'\)\)&&profile\.artifact_id\)/)
assert.match(owner,/r\.active=1 JOIN sponsor_artifacts/)
assert.match(owner,/a\.sponsor_id=\? AND sa\.artifact_id=\? AND a\.active=1/)
assert.match(owner,/parsed\.protocol==='https:'/)
assert.match(owner,/Cache-Control','private, no-store/)
assert.doesNotMatch(owner,/\bUPDATE\b|\bINSERT\b|\bDELETE\b/)
assert.match(view,/import SponsoredCommercialOwnerBar from '\.\/SponsoredCommercialOwnerBar'/)
assert.match(view,/<SponsoredCommercialOwnerBar username=\{data\.username\} apiOrigin=\{appOrigin\(\)\}\/>/)
assert.match(bar,/fetch\(apiOrigin\.replace/)
assert.match(bar,/credentials:'include',cache:'no-store'/)
assert.match(bar,/setLinks\(null\)/)
assert.match(bar,/if\(!links\|\|\( !links\.contact_url && !links\.resource_url\)\)return null/)
assert.match(bar,/Mi patrocinador · Acceso privado/)
assert.match(bar,/target="_blank" rel="noopener noreferrer"/)
assert.match(admin,/me\/sponsored-profile\/commercial-links/)
assert.match(account,/m\[3\]!==fingerprint/)
console.log('Private sponsored commercial bar: owner, Master, beneficiary, multiaccount, assignment, grants and visitor isolation checks OK')
