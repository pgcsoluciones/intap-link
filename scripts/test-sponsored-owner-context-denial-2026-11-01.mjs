import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const api=readFileSync('api/src/sponsored-appointments.ts','utf8')
const scope=readFileSync('api/src/sponsored-profile-scope.ts','utf8')
const selection=readFileSync('api/src/intap-active-account.ts','utf8')
const ownerBar=readFileSync('web/src/components/appointments/AppointmentOwnerBar.tsx','utf8')
const start=api.indexOf("app.get('/api/v1/me/sponsored-profile/appointments/public-context'")
const end=api.indexOf('\nexport default app',start)
assert.ok(start>=0&&end>start,'public owner-context route exists')
const block=api.slice(start,end)
assert.match(block,/requireUser,async/)
assert.match(block,/WHERE username=\? AND user_id=\? LIMIT 1/)
assert.match(block,/if\(!profile\)return c\.json\(\{ok:false,error:'Not owner'\},403\)/)
assert.match(block,/if\(await sponsoredMultiProfileAccess\(c,userId\)\)/)
assert.match(block,/const active=await readIntapSelection\(c\)/)
assert.match(block,/if\(!active\)return c\.json\(\{ok:false,error:ownerSelectionError,code:'owner_selection_missing'\},403\)/)
assert.match(block,/const requiredKind=isMaster\?'sponsor':'sponsored'/)
assert.match(block,/if\(active\.kind!==requiredKind\)return c\.json\(\{ok:false,error:ownerSelectionError,code:'owner_account_category_mismatch'\},403\)/)
assert.match(block,/const requiredId=isMaster\?String\(\(profile as any\)\.sponsor_id\|\|''\):subjectId/)
assert.match(block,/if\(active\.id!==requiredId\)return c\.json\(\{ok:false,error:ownerSelectionError,code:'owner_account_identity_mismatch'\},403\)/)
assert.match(block,/is_owner:true/)
assert.doesNotMatch(block,/\bUPDATE\b|\bDELETE\b|\bINSERT\b/)
assert.doesNotMatch(block,/code:.*(requiredId|active\.id|session|token)/)
assert.match(scope,/if\(multi&&active\?\.kind!=='sponsor'\)return null/)
assert.match(selection,/m\[3\]!==fingerprint/)
assert.match(ownerBar,/if\(!context\)return null/)
console.log('Public owner-context denial is scoped, non-sensitive and fail-closed: OK')
