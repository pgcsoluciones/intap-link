import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const src=readFileSync('prototypes/kawvo-mobile-shell-2026-11-12/index.html','utf8')
const script=src.match(/<script>([\s\S]*?)<\/script>/)?.[1]||''
assert.ok(script,'Interactive script must be available')
assert.match(src,/PROTOTIPO INTERACTIVO/,'Always tell visitor this is a demo')
assert.match(src,/SIN DATOS REALES NI OPERACIONES/,'Demo cannot pass as live system')
for(const key of ['free:','paid:','med:','beneficiary:','sponsor:'])assert.ok(src.includes(key),'Role missing: '+key)
for(const label of ['Inicio','Perfil','Agenda','Más'])assert.ok(src.includes(label),'Unified navigation missing '+label)
assert.match(src,/role==="sponsor"\?\[\["home".*?"sponsorOps".*?\["more"/,'Sponsor-specific operations are first-class but shell stays recognizable')
assert.match(src,/function sponsorHome\(\)/,'Sponsor home exists')
assert.match(src,/function sponsorOps\(\)/,'Sponsor inventory/assignments exist')
assert.match(src,/function renderSponsorResults\(\)/,'Search and filter results render')
assert.match(src,/sponsorView==="devices"\?\[\["all","Todos"/,'Device statuses are filterable')
assert.match(src,/Buscar por estación, persona o zona/,'Nontechnical search language')
assert.match(src,/data-sponsor-item/,'Device detail is explorable')
assert.match(src,/Departamento \/ zona/,'Assignment department/territory is visible')
assert.match(src,/Perfil destinatario/,'Assigned profile is visible')
assert.match(src,/Revisar asignación · demo/,'Action clearly labeled demo')
assert.match(src,/No se asigna, activa ni transfiere ningún código/,'Do not imply real activation')
assert.match(src,/Mi presentación Master/,'Own profile is separate')
assert.match(src,/Marca e identidad comercial/,'Business identity is separate')
assert.match(src,/Permisos del equipo/,'Permissions remain distinct')
assert.match(src,/visitadores autorizados|Visitadora/,'Commercial delegation preserved in content')
assert.match(src,/min-height:44px/,'Touch areas sized for phones')
assert.match(src,/safe-area-inset-bottom/,'Respects mobile safe area')
assert.match(src,/@media\s*\(min-width:700px\)/,'Tablet/desktop adaptation exists')
assert.doesNotMatch(script,/fetch\(|XMLHttpRequest|sendBeacon|WebSocket|EventSource|localStorage|sessionStorage|apiPost\(|apiGet\(|window\.location\.(assign|replace)/i,'Prototyping must remain disconnected')
assert.doesNotMatch(src,/googleapis\.com|places\.google|reviews\.google|Google Business Profile API|data-action="reviews"/i,'Future Reviews feature must not be built now')
assert.doesNotMatch(src,/<form\b/i,'No live forms or accidental submissions')
console.log('PASS: Kawvo Master mobile prototype, device/assignment discovery, role-safe offline-only contracts')
