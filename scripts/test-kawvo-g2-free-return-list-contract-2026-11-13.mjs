import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

// G2.2 static contract; authenticated click/scroll/save QA is still mandatory.
const src=(p)=>readFileSync(p,'utf8')
const shell=src('app/src/components/admin/free/KawvoFreeShellPreview.tsx')
const list=src('app/src/components/admin/shared/KawvoPagedList.tsx')
const state=src('app/src/components/admin/free/KawvoShellReturn.ts')
const back=src('app/src/components/admin/free/FreePanelUi.tsx')
const editor=src('app/src/components/admin/free/FreeVisualEditor.tsx')
const agenda=src('app/src/components/admin/free/FreeAppointments.tsx')
const account=src('app/src/components/admin/free/FreeAccount.tsx')
const notices=src('app/src/components/admin/free/FreeNotifications.tsx')
const legacy=src('app/src/components/admin/free/FreeDashboard.tsx')
const app=src('app/src/App.tsx')

// No privilege, identity or account switch authority is generated by URL/history state.
assert.match(state,/kawvoShellReturn: true/,'The navigation-only marker remains explicit')
assert.match(state,/kawvoShellAccount: string/,'Account scope travels with the return hint')
assert.match(state,/typeof state\.kawvoShellAccount !== 'string'/,'Untrusted account hints are validated')
assert.match(state,/tabs\.includes\(state\.kawvoShellTab as KawvoShellTab\)/,'Tab value is restricted')
assert.match(state,/isKawvoShellPreviewHost/,'The return context is Preview-only')
assert.match(state,/import\.meta\.env\.MODE === 'preview'/,'Production builds cannot use the return shortcut')
assert.match(state,/window\.location\.hostname === 'app\.preview\.intaprd\.com'/,'Only authenticated App Preview host may return')
assert.match(shell,/const incomingReturn=getKawvoShellReturn\(location\.state\)/,'Restoration reads navigation state')
assert.match(shell,/incomingReturn\.kawvoShellAccount!==activeAccount/,'No cross-account tab restoration')
assert.match(shell,/setTab\(incomingReturn\.kawvoShellTab==='agenda'/,'Origin tab is restored only when allowed')
assert.match(shell,/const verifiedReturn=incomingReturn\?\.kawvoShellAccount===accountIdentity\?incomingReturn:null/,'List state is ignored for another account')
assert.match(shell,/kawvoShellTab:tab,kawvoShellAccount:accountIdentity/,'Each opened module inherits exact origin tab/account')
assert.match(shell,/kawvoShellList:listState,kawvoShellItem:id/,'Search/group and clicked item travel back')
assert.match(back,/getKawvoShellReturn\(location\.state\)/,'Back handler validates the incoming hint')
assert.match(back,/if \(returnContext\.kawvoShellViaEditor\)/,'Nested editor sections go back to visual editor first')
assert.match(back,/navigate\('\/admin\/free\/editor', \{state:\{\.\.\.returnContext,kawvoShellViaEditor:false\}\}\)/,'Editor nested return retains original state')
assert.match(back,/navigate\(KAWVO_SHELL_PREVIEW_ROUTE, \{state:returnContext\}\)/,'Shell return keeps tab and filter')
assert.match(back,/onClick\(event\)/,'Original back handler survives for legacy and production')
assert.match(editor,/shellReturn \? \{state:\{\.\.\.shellReturn,kawvoShellViaEditor:true\}\} : undefined/,'Editor submodule navigation propagates return chain')
assert.match(agenda,/returnToShell\?\{state:location\.state\}:undefined/,'Agenda returns with originating state')
assert.match(agenda,/apiBase="\/me\/free\/appointments"/,'Agenda data endpoint remains unchanged')
assert.match(account,/const backToProfile = \(\) => navigate\(shellReturn \? KAWVO_SHELL_PREVIEW_ROUTE : '\/admin\/free'/,'Account back retains prior shell when opted in')
assert.match(notices,/shellReturn \? KAWVO_SHELL_PREVIEW_ROUTE : '\/admin\/free'/,'Notifications back retains the origin')
assert.match(notices,/fromAccount \? '\/admin\/free\/account'/,'Notifications from Account still return to Account')

// Seven navigation items are a SMALL fixed menu: vertical scrolling, not a second screen.
assert.match(shell,/onOpen=\{go\} paginated=\{false\}/,'Profile menu explicitly opts out of pagination')
assert.match(list,/paginated\?filtered\.slice\(\(safePage-1\)\*size,safePage\*size\):filtered/,'Continuous menu renders all filtered items')
assert.match(list,/paginated&&pages>1&&<nav/,'Other paginated consumers remain intact')
assert.match(list,/onOpen\(item\.id,\{query,group\}\)/,'Search and filter are preserved on exit')
assert.match(list,/scrollIntoView\(\{block:'center',behavior:'auto'\}\)/,'Last clicked module is visible on return')
assert.match(list,/id=\{'kawvo-menu-item-'\+item\.id\}/,'Menu item exposes an anchor for return scroll')
assert.doesNotMatch(shell,/apiPut\(|apiPost\(|apiPatch\(|apiDelete\(|apiUpload\(/,'Shell cannot change data itself')
assert.match(app,/path="\/admin\/free\/shell-preview" element=\{<AdminGuard planScope="free">/,'Existing Free route guard remains')
assert.match(legacy,/const togglePublished = async \(\) =>/,'Publish remains authoritative in original dashboard')
console.log('PASS: G2.2 account-scoped tab/filter/scroll return, continuous Free menu, legacy paths intact')
