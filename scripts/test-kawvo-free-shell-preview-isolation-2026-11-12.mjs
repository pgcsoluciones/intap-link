import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const app=readFileSync('app/src/App.tsx','utf8')
const shell=readFileSync('app/src/components/admin/free/KawvoFreeShellPreview.tsx','utf8')
const list=readFileSync('app/src/components/admin/shared/KawvoPagedList.tsx','utf8')
const free=readFileSync('app/src/components/admin/free/FreeDashboard.tsx','utf8')
const routes=readFileSync('app/src/components/admin/free/FreeRouteUx.tsx','utf8')
const contract=readFileSync('docs/architecture/KAWVO_LARGE_LIST_SEARCH_FILTER_PAGINATION_CONTRACT_2026-11-12.md','utf8')
assert.match(app, /<Route path="\/admin\/free\/shell-preview" element=\{<AdminGuard planScope="free"><KawvoFreeShellPreview\/><\/AdminGuard>\}\/>/,'Shell route uses existing Free guard')
assert.match(app, /<Route path="\/admin\/free" element=\{<AdminGuard planScope="free"><FreeDashboard\/><\/AdminGuard>\}\/>/,'Original Free panel route unmodified')
assert.match(shell, /import\.meta\.env\.MODE==='preview'/,'Preview build only')
assert.match(shell, /window\.location\.hostname==='app\.preview\.intaprd\.com'/,'Private Preview host only')
assert.match(shell, /get\('kawvo_shell'\)==='1'/,'Explicit opt-in required')
assert.match(shell, /if\(!enabled\)return <Navigate to="\/admin\/free" replace\/>/,'Unapproved host or navigation falls back to old panel')
assert.match(shell, /apiGet\('\/me'\)/,'Same account context')
assert.match(shell, /apiGet\('\/me\/team\/context'\)/,'Team context is read')
assert.match(shell, /!profile\|\|!team/,'Fail closed for absent team context')
assert.match(shell, /team\.role==='member'/,'Team member treatment')
assert.match(shell, /onOpen=\{go\}/,'Existing routes opened from list')
assert.match(shell, /navigate\('\/admin\/free'\)/,'Publication and previews delegate to old panel')
assert.doesNotMatch(shell, /apiPost\(|apiPut\(|apiPatch\(|apiDelete\(|apiUpload\(/,'Opt-in shell never writes')
assert.doesNotMatch(shell, /fetch\(/,'No direct API bypass')
assert.doesNotMatch(shell, /\/me\/profile.*is_published|togglePublished|setPublished/,'Publication logic not copied')
assert.doesNotMatch(shell, /window\.location\.assign|window\.location\.replace/,'No cross-host redirect from shell')
assert.match(list, /filtered\.slice\(\(safePage-1\)\*size,safePage\*size\)/,'Client pagination limited to prebounded menus')
assert.match(list, /Math\.min\(25,/,'Maximum page size bounded')
assert.match(list, /setPage\(1\)/,'Filter resets the page')
assert.match(list, /Buscar una función/,'Search provided')
assert.match(list, /Filtrar módulos/,'Filters provided')
assert.match(list, /Paginación de funciones/,'Previous/next navigation provided')
assert.match(contract,/búsqueda, filtrado y paginación DEBEN suceder en API\/D1/,'Large collections require backend pagination')
assert.match(contract,/roles/,'All role scopes included')
assert.match(free,/if \(next === 1 && !effectivePublishReady\)/,'Current Free publication readiness guard retained')
assert.match(free,/disabled=\{publishing \|\| \(!me\?\.is_published && !effectivePublishReady\)\}/,'Current Free publish control remains disabled until ready')
assert.match(free,/result\.error === 'profile_incomplete'/,'Server rejects incomplete Free publication')
assert.match(free,/setMe\(\{ \.\.\.me, is_published: next \}\)/,'Published state is changed only following successful server response')
assert.match(free,/apiPut\('\/me\/profile'/,'Approved publish API untouched')
assert.match(routes,/kawvo-free-mobile/,'Existing mobile route UX available')
console.log('PASS: opt-in Preview-only Free shell, existing publication and role guards, bounded search/filter/pagination contract')
