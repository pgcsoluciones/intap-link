import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read=p=>readFileSync(p,'utf8')
const core=read('api/src/index.ts')
const free=read('api/src/free-appointments.ts')
const sponsored=read('api/src/sponsored-appointments.ts')
const medical=read('api/src/medical-appointments.ts')
const web=read('web/src/components/appointments/AppointmentOwnerBar.tsx')
const freeProfile=read('web/src/components/free-profile/IntapLinkGratisProfile.tsx')
const shortcut=read('web/src/components/free-profile/FreePreviewEditShortcut.tsx')

const middleware=core.slice(core.indexOf('// Classic Free/Link editor requests from another tab'),core.indexOf('registerDemoViralRoutes(app)'))
assert.ok(middleware.length>500,'Free classic middleware present')
assert.match(middleware,/if\(c\.req\.method==='GET'&&path==='\/api\/v1\/me\/free\/appointments\/public-context'\)return next\(\)/,'Exact read-only Free owner context bypass')
assert.ok(middleware.indexOf("path==='/api/v1/me/free/appointments/public-context'")<middleware.indexOf("if(!matchesActiveIntapTab(c,active))"),'Bypass precedes tab-token guard')
assert.match(middleware,/if\(!matchesActiveIntapTab\(c,active\)\)return c\.json\(/,'Mutation protection unchanged')
assert.doesNotMatch(middleware,/startsWith\('\/api\/v1\/me\/free\/appointments'\).*return next\(\)/,'Do not exempt all Free appointments endpoints')
assert.match(core,/endsWith\('\/appointments\/public-context'\)\)return next\(\)/,'Sponsor and medical owner-context exceptions remain')
assert.match(sponsored,/app\.get\('\/api\/v1\/me\/sponsored-profile\/appointments\/public-context',requireUser/,'Sponsored comparison route')
assert.match(medical,/app\.get\('\/api\/v1\/me\/medical-profile\/appointments\/public-context',requireUser/,'Medical comparison route')
const route=free.slice(free.indexOf("app.get('/api/v1/me/free/appointments/public-context'"))
assert.match(route,/requireUser/,'Session required')
assert.match(route,/WHERE lower\(slug\)=\? AND user_id=\?/,'Owner and public slug verified in database')
assert.match(route,/const multi=await sponsoredMultiProfileAccess\(c,userId\)/,'Special multicuenta checks')
assert.match(route,/if\(!selected\|\|selected\.kind!=='free'\|\|selected\.id!==subjectId\)/,'Exact selection type and identity required')
assert.match(route,/code:'owner_account_selection_mismatch'/,'Safe failure code')
assert.match(route,/allow_direct_actions:!multi/,'No public direct mutations for multicuenta')
assert.match(route,/settings_url:'\/admin\/free\/account'/,'Same admin destination')
assert.match(web,/credentials:'include'/,'Owner session credentials included')
assert.match(web,/if\(json\?\.ok&&json\.data\?\.is_owner\)setContext\(json\.data\)/,'No owner bar for visitors')
assert.match(freeProfile,/\{showOwnerBar && <AppointmentOwnerBar/,'Free mounts shared ownerbar')
assert.match(shortcut,/slots\.desktop&&createPortal\(link,slots\.desktop/,'Return editor remains inside toolbar')
assert.doesNotMatch(shortcut,/position:'fixed'/,'Never overlay preview shortcut')
console.log('PASS: Free multicuenta middleware parity with sponsored/KawMed; only exact GET exempt; session+owner+selection and mutations remain protected')
