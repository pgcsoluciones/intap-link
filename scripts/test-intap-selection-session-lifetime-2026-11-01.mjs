assert.match(selection,/crypto.randomUUID\(\)\.replace\(\/-\/g,''\)/)
assert.match(selection,/received===selection.tabToken/)
assert.match(selection,/export function clearIntapSelection\(c:any\)/)
assert.match(home,/if\(!selected\|\|!\(await ownedChoice\(c,userId,selected.kind,selected.id\)\)\)/)
assert.match(home,/if\(!\/^\[a-f0-9-\]\{36\}\$\/i\.test\(id\)\|\|!\(await ownedChoice\(c,userId,kind,id\)\)\)/)
assert.match(home,/const tabToken=await setIntapSelection\(c,\{kind,id\}\)/)
assert.match(appSelector,/sessionStorage.setItem\(INTAP_ACTIVE_TAB_STORAGE,token\)/)
assert.match(sponsored,/if\(!active\)return c\.json\(\{ok:false,error:ownerSelectionError,code:'owner_selection_missing'\},403\)/)
assert.match(sponsored,/if\(active\.kind!==requiredKind\)return/)
assert.match(sponsored,/if\(active\.id!==requiredId\)return/)
